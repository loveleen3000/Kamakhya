const VALUE_MAP_HI = {};
[...MOODS, ...SYMPTOMS, ...CATEGORIES].forEach((i) => {
  VALUE_MAP_HI[i.en] = i.hi;
});
DEFAULT_TASKS.forEach((i) => {
  VALUE_MAP_HI[i.en] = i.hi;
  if (i.noteEn) VALUE_MAP_HI[i.noteEn] = i.noteHi;
});

